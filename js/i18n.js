  const params = new URLSearchParams(location.search);
  let stored = "";
  try { stored = localStorage.getItem("neha-language") || ""; } catch (_) {}
  const requested = params.get("lang");
  const language = requested === "es" || requested === "en" ? requested : stored === "es" ? "es" : "en";
  if (requested === "es" || requested === "en") {
    try { localStorage.setItem("neha-language", requested); } catch (_) {}
  }
  document.documentElement.lang = language;

  const t = value => language === "es" ? (ES[String(value)] ?? String(value)) : String(value);
  const field = (item, name) => language === "es" && item && item[`${name}Es`] ? item[`${name}Es`] : item?.[name];

  function setLanguage(next) {
    if (next !== "en" && next !== "es") return;
    try { localStorage.setItem("neha-language", next); } catch (_) {}
    const url = new URL(location.href);
    if (next === "es") url.searchParams.set("lang", "es");
    else url.searchParams.delete("lang");
    location.href = url.pathname.split("/").pop() + (url.searchParams.toString() ? `?${url.searchParams}` : "") + url.hash;
  }

  function translateTextNode(node) {
    if (!node.nodeValue || !node.nodeValue.trim()) return;
    const raw = node.nodeValue;
    const key = raw.trim();
    const translated = t(key);
    if (translated === key) return;
    node.nodeValue = raw.replace(key, translated);
  }

  function apply(root) {
    if (language !== "es") return;
    const scope = root || document;
    const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        const tag = node.parentElement?.tagName;
        return tag && !["SCRIPT", "STYLE", "NOSCRIPT", "TEXTAREA"].includes(tag)
          ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(translateTextNode);
    const elements = scope.querySelectorAll ? scope.querySelectorAll("[placeholder], [aria-label], [title], [data-label], [data-placeholder]") : [];
    elements.forEach(el => ["placeholder", "aria-label", "title", "data-label", "data-placeholder"].forEach(attr => {
      if (el.hasAttribute(attr)) el.setAttribute(attr, t(el.getAttribute(attr)));
    }));
  }

  window.NEHA_I18N = { language, t, field, apply, setLanguage };
